"""Builds styles/scss/foundation/_icon-list.scss from the files in assets/icons/.

Lists every single-colour icon (ico-{name}.svg) for the .icon--{name} classes in
styles/scss/foundation/_icon.scss. Channel colour icons (*-color) and national
flags (ico-flag-*) keep their own colours, so they stay <img> and are left out.

Run from the repo root after adding or removing an icon, then build the CSS:
    python3 tools/icon-build/build_icon_list.py > styles/scss/foundation/_icon-list.scss
"""

import os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
names = sorted(
    f[len('ico-'):-len('.svg')]
    for f in os.listdir(os.path.join(ROOT, 'assets', 'icons'))
    if f.startswith('ico-') and f.endswith('.svg') and '-color' not in f and not f.startswith('ico-flag-')
)

print('// Generated by tools/icon-build/build_icon_list.py from assets/icons/ — do not edit by hand.')
print('// Single-colour icons only (no *-color, no ico-flag-*): one .icon--{name} class each.')
print()
print('$icons: (')
for n in names:
    print(f"  '{n}',")
print(');')
